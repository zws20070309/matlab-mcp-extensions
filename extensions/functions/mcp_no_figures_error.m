function mcp_no_figures_error(who)
%MCP_NO_FIGURES_ERROR Explain an empty figure list, naming the real cause.
%   Three distinct situations produce "no open figures" and they need different
%   actions; the old tools all reported the same bare sentence:
%     1. nodesktop mode: figures do not survive between tool calls (measured
%        2026-11-04 on v0.16.0: a figure created in one call is gone in the next
%        while gcf still hands back a dead handle). Nothing the caller can do
%        inside the tool - the server must run with --matlab-display-mode=desktop.
%     2. desktop mode but the caller closed the figure / never created one.
%     3. a different MATLAB session than the one holding the figure (auto mode
%        attaches to a session that may not be the one the user is looking at).
%   Detecting (1) is possible from inside MATLAB: nodesktop sessions report no
%   figure support through usejava('desktop').
desktop = true;
try
    desktop = usejava('desktop');
catch
end
if ~desktop
    error([who ':noFiguresNodesktop'], [ ...
        '[%s:noFiguresNodesktop] No figures are open, and this MATLAB runs in ' ...
        'NODESKTOP mode, where a figure created by one tool call does not survive ' ...
        'into the next call (measured on v0.16.0: the figure list is empty on the ' ...
        'following call while gcf still returns a stale handle). ' ...
        'Two ways forward: (a) restart the MCP server with ' ...
        '--matlab-display-mode=desktop so figures persist between calls, or ' ...
        '(b) export inside the SAME call that draws: ' ...
        'evaluate_matlab_code("f=figure; plot(x); exportgraphics(f,''out.png'')").'], who);
end
error([who ':noFigures'], [ ...
    '[%s:noFigures] No open figures to capture. Create one first (figure/plot), ' ...
    'or check that you are talking to the session that holds it: with ' ...
    '--matlab-session-mode=auto the server may have attached to a different ' ...
    'MATLAB than the desktop you are looking at (session_info shows pwd/pid).'], who);
end
